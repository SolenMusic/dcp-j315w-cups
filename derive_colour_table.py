#!/usr/bin/env python3
"""Measure ink-code distributions from the controlled 9x9x9 RGB cube capture.

The table contains observed output behaviour, not vendor executable code or an
ICC file. Fixtures are generated by make_quality_probe.c using its cube mode.
"""
from pathlib import Path
import sys

data = Path(sys.argv[1]).read_bytes()
assert data[:4096] == bytes(4096) and data[-4096:] == bytes(4096)
p = 4916
assert data[p:p + 2] == b"I1"
p += 2
hist = [[[0] * 4 for _ in range(4)] for _ in range(729)]
region = -1

while data[p:p + 1] == b"F":
    assert data[p:p + 3] == b"F\x88\x0e"
    p += 3
    region += 1
    if data[p:p + 5] != b"ivT2\x01":
        continue
    p += 5
    for record in range(93 * 5):
        slot = record % 5
        command = data[p]
        p += 1
        payload = None
        if command == ord("G"):
            size = int.from_bytes(data[p:p + 2], "little")
            p += 2
            payload = data[p:p + size]
            p += size
        else:
            assert command == ord("Z")
        if slot == 3:
            assert command == ord("Z")
            continue
        phase = region % 4
        y = (region // 4 * 93 + record // 5 - (3 - phase) * 23) * 4 + phase
        channel = 3 if slot == 4 else slot
        if channel != 3:
            y -= 2
        if not 32 <= y < 32 + 27 * 64 or not 8 <= (y - 32) % 64 < 56:
            continue
        tile_y = (y - 32) // 64
        line = bytearray()
        if payload is not None:
            q = 0
            while q < len(payload):
                control = payload[q]
                q += 1
                count = control >> 5
                line.extend(bytes(control & 31))
                line.extend(payload[q:q + count])
                q += count
                assert q <= len(payload)
            assert len(line) == 582
        for tile_x in range(27):
            h = hist[tile_y * 27 + tile_x][channel]
            if payload is None:
                h[0] += 48
            else:
                left = (32 + tile_x * 64 + 8) // 4
                for value in line[left:left + 12]:
                    for shift in (0, 2, 4, 6):
                        h[(value >> shift) & 3] += 1

assert data[p:] == b"\x0c\x1b@" + bytes(4096)
table = []
for node in hist:
    entry = []
    for channel in node:
        assert sum(channel) == 48 * 48
        # Survival probabilities P(code>=1), P(code>=2), P(code>=3).
        # Matching these retains the distribution of small/medium/large dots.
        values = [round(255 * sum(channel[level:]) / (48 * 48)) for level in (1, 2, 3)]
        assert values[0] >= values[1] >= values[2]
        entry.append(values)
    table.append(entry)
assert table[-1] == [[0, 0, 0]] * 4

with Path(sys.argv[2]).open("w") as out:
    out.write("// Generated by derive_colour_table.py from controlled RGB patches.\n")
    out.write("// 600 dpi, plain paper, Natural colour, Diffusion reference output.\n")
    out.write("// Nodes are RGB 0,32,64,96,128,160,192,224,255, in R/G/B order.\n")
    out.write("// Each channel holds P(code>=1), P(code>=2), P(code>=3), scaled to 255.\n")
    out.write("static const unsigned char colour600_table[729][4][3] = {\n")
    for entry in table:
        out.write("  {" + ", ".join("{" + ",".join(map(str, c)) + "}" for c in entry) + "},\n")
    out.write("};\n")

for rgb in ((0, 0, 0), (128, 128, 128), (192, 192, 192), (255, 0, 0), (255, 255, 255)):
    levels = [8 if v == 255 else v // 32 for v in rgb]
    entry = table[(levels[0] * 9 + levels[1]) * 9 + levels[2]]
    print(rgb, "mean C/M/Y/K codes:", [round(sum(c) / 255, 3) for c in entry])
